// 記事のフロントマターの ownServices（キーの配列）を、表示用のデータにする
export function resolveOwnServices(list) {
  if (!Array.isArray(list)) return [];
  return [...new Set(list.map(String))].filter((id) => OWN_SERVICES[id]).map((id) => OWN_SERVICES[id]);
}
